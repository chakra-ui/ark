import * as datePicker from '@zag-js/date-picker'
import { controlled, num, positioning, positioningAttributes, str } from '../../utils/attrs.js'
import { definePresenceRoot } from '../../utils/presence.js'
import { date, dates, root } from './shared.js'

definePresenceRoot<datePicker.Api>({
  properties: ['createCalendar', 'isDateUnavailable', 'format', 'parse', 'ids', 'translations', 'positioning'],

  tag: root,
  machine: datePicker.machine,
  connect: datePicker.connect,
  present: (api) => api.open,
  attributes: [
    'value',
    'default-value',
    'min',
    'max',
    'locale',
    'time-zone',
    'selection-mode',
    'max-selected-dates',
    'num-of-months',
    'start-of-week',
    'fixed-weeks',
    'show-week-numbers',
    'close-on-select',
    'open-on-click',
    'outside-day-selectable',
    'view',
    'default-view',
    'min-view',
    'max-view',
    'open',
    'default-open',
    'inline',
    'disabled',
    'readonly',
    'required',
    'invalid',
    'name',
    'placeholder',
    ...positioningAttributes,
  ],
  props: (el) => ({
    value: dates(el, 'value'),
    defaultValue: dates(el, 'default-value'),
    min: date(el, 'min'),
    max: date(el, 'max'),
    locale: str(el, 'locale'),
    timeZone: str(el, 'time-zone'),
    selectionMode: str<datePicker.SelectionMode>(el, 'selection-mode'),
    maxSelectedDates: num(el, 'max-selected-dates'),
    numOfMonths: num(el, 'num-of-months'),
    startOfWeek: num(el, 'start-of-week'),
    fixedWeeks: el.hasAttribute('fixed-weeks'),
    showWeekNumbers: el.hasAttribute('show-week-numbers'),
    closeOnSelect: el.getAttribute('close-on-select') !== 'false',
    openOnClick: el.hasAttribute('open-on-click'),
    outsideDaySelectable: el.hasAttribute('outside-day-selectable'),
    view: str<datePicker.DateView>(el, 'view'),
    defaultView: str<datePicker.DateView>(el, 'default-view'),
    minView: str<datePicker.DateView>(el, 'min-view'),
    maxView: str<datePicker.DateView>(el, 'max-view'),
    open: controlled(el, 'open'),
    defaultOpen: el.hasAttribute('default-open'),
    inline: el.hasAttribute('inline'),
    disabled: el.hasAttribute('disabled'),
    readOnly: el.hasAttribute('readonly'),
    required: el.hasAttribute('required'),
    invalid: el.hasAttribute('invalid'),
    name: str(el, 'name'),
    placeholder: str(el, 'placeholder'),
    positioning: positioning(el),
  }),
  events: {
    onValueChange: 'valuechange',
    onFocusChange: 'focuschange',
    onViewChange: 'viewchange',
    onVisibleRangeChange: 'visiblerangechange',
    onOpenChange: 'openchange',
  },
  rootProps: (api) => api.getRootProps(),
})
