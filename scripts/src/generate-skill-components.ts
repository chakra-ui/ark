import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, '../..')
const pages = join(root, 'website/src/content/pages')
const out = join(root, 'skills/ark-ui/references/components.md')

const exportsOf = (pkg: string) =>
  Object.keys(JSON.parse(readFileSync(join(root, 'packages', pkg, 'package.json'), 'utf8')).exports)
const reactExports = exportsOf('react')
const webExports = exportsOf('web')

const entryOverrides: Record<string, string> = {
  'progress-circular': 'progress',
  'progress-linear': 'progress',
  'format-byte': 'format',
  'format-number': 'format',
  'format-relative-time': 'format',
  'format-time': 'format',
}

const webEntryOverrides: Record<string, string> = {
  'async-list': 'async-list',
}

interface Page {
  slug: string
  title: string
  description: string
  entry: string
  webEntry: string
  web: boolean
}

const readFrontmatter = (file: string) => {
  const match = readFileSync(file, 'utf8').match(/^---\n([\s\S]*?)\n---/)
  const fields: Record<string, string> = {}
  let key = ''
  for (const line of match?.[1].split('\n') ?? []) {
    const field = line.match(/^(\w+):\s*(.*)$/)
    if (field) {
      key = field[1]
      fields[key] = field[2]
    } else if (key) {
      fields[key] += ` ${line.trim()}`
    }
  }
  for (const k in fields) fields[k] = fields[k].trim().replace(/^"|"$/g, '')
  return fields
}

const readPages = (section: string): Page[] =>
  readdirSync(join(pages, section))
    .filter((file) => file.endsWith('.mdx') && file !== 'overview.mdx')
    .map((file) => {
      const slug = file.replace('.mdx', '')
      const { title = slug, description = '' } = readFrontmatter(join(pages, section, file))
      const entry = section === 'collections' ? 'collection' : (entryOverrides[slug] ?? slug)
      if (!existsSync(join(root, 'packages/react/src/components', entry)) && !reactExports.includes(`./${entry}`)) {
        throw new Error(`${section}/${file}: no @ark-ui/react/${entry} entry`)
      }
      return {
        slug,
        title,
        description,
        entry,
        webEntry: webEntryOverrides[slug] ?? entry,
        web: webExports.includes(`./${webEntryOverrides[slug] ?? entry}`),
      }
    })
    .sort((a, b) => a.title.localeCompare(b.title, 'en'))

const importOf = (page: Page) => {
  const entry = `\`@ark-ui/{framework}/${page.entry}\``
  return page.web && page.webEntry !== page.entry ? `${entry}, web: \`@ark-ui/web/${page.webEntry}\`` : entry
}

const table = (section: string) => {
  const rows = readPages(section).map(
    (page) =>
      `| ${page.title} | \`${page.slug}\` | ${importOf(page)} | ${page.web ? 'Yes' : 'No'} | ${page.description.replaceAll('|', '\\|')} |`,
  )
  return ['| Name | Slug | Import | Web | What it is |', '| --- | --- | --- | --- | --- |', ...rows].join('\n')
}

const markdown = `<!-- Generated by \`bun run skill:components\` from website/src/content/pages. Don't edit by hand. -->

# Components

Each page is at \`{docs}/docs/{framework}/{section}/{slug}.md\`, where the framework is \`react\`, \`solid\`, \`vue\`,
\`svelte\` or \`web\`. Import from the entry in the Import column, never from the package root. The Web column says
whether \`@ark-ui/web\` ships it.

## Components

Section: \`components\`.

${table('components')}

## Utilities

Section: \`utilities\`.

${table('utilities')}

## Collections

Section: \`collections\`. Select, Combobox, Listbox and Tree View take a collection, not an \`items\` array.

${table('collections')}
`

writeFileSync(out, markdown)
console.log(`Wrote ${out}`)
